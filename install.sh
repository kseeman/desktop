#!/usr/bin/env bash

set -euo pipefail

# -----------------------------------------------------------------------------
# Desktop installation
# -----------------------------------------------------------------------------
#
# Installs the Lua Hyprland desktop on top of the dotfiles, which must already
# be installed: the shell, nvim, tmux and kitty are theirs, and this repo only
# themes them, by writing $XDG_CACHE_HOME/dotfiles/theme/ for them to read.
#
# The helpers come from the dotfiles' lib/install.sh rather than being copied,
# so linking, backups and package installs behave the same in both repos. That
# makes the dependency one way: this repo knows about the dotfiles, and the
# dotfiles know only a cache path.

# -----------------------------------------------------------------------------
# Variables
# -----------------------------------------------------------------------------

DESKTOP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DRY_RUN=false

# Resolved rather than assumed, the same way snapshot.sh does.
XDG_CONFIG="${XDG_CONFIG_HOME:-$HOME/.config}"

for arg in "$@"; do
    case "$arg" in
        --dry-run)
            DRY_RUN=true
            ;;
    esac
done

# -----------------------------------------------------------------------------
# The dotfiles
# -----------------------------------------------------------------------------

if [[ ! -f "$HOME/.dotfiles/lib/install.sh" ]]; then
    echo "The dotfiles are not installed: ~/.dotfiles/lib/install.sh is missing."
    echo "Run the dotfiles' install.sh first; this desktop is installed on top."
    exit 1
fi

DOTFILES_DIR="$(cd "$HOME/.dotfiles" && pwd -P)"

source "$DOTFILES_DIR/lib/os.sh"
source "$DOTFILES_DIR/lib/install.sh"

# Links into any of these are this install's own, and are replaced without a
# backup. The dotfiles are included because this desktop used to live there:
# ~/.config/hypr/scripts and the hyde/ links pointed into it, and re-pointing
# them here is a move, not a takeover.
REPO_ROOTS=("$DESKTOP_DIR" "$HOME/.dotfiles" "$DOTFILES_DIR")

if [[ "$(dotfiles_detect_os)" != "linux" || "$(dotfiles_detect_distro)" != "arch" ]]; then
    echo "This desktop is Hyprland on an Arch-based Linux, and this is not one."
    exit 1
fi

info "Installing the desktop from:"
echo "$DESKTOP_DIR"

if [[ "$DRY_RUN" == true ]]; then
    echo "Running in dry-run mode. No changes will be made."
fi

# -----------------------------------------------------------------------------
# Packages
# -----------------------------------------------------------------------------

install_pacman_manifest "$DESKTOP_DIR/packages/pacman.txt"
install_aur_manifest "$DESKTOP_DIR/packages/aur.txt"

# -----------------------------------------------------------------------------
# HyDE's user-tier Hyprland files
# -----------------------------------------------------------------------------

# Linked into ~/.config/hypr. Inert since HyDE was removed -- nothing sources
# them -- and kept because reinstalling HyDE would want them and they record
# bindings worth consulting.
#
# Deliberately NOT linked (and not tracked at all):
#   monitors.conf, workspaces.conf  generated by nwg-displays; both name
#                                   physical outputs (monitor:DP-1, DP-2)
#   nvidia.conf                     hardware-specific
#
# All of them describe *this* machine's hardware, so they would be wrong on any
# other one, and the nwg-displays pair is regenerated by that tool — tracking
# them means fighting it on every display rearrangement.
HYPR_USER_CONFIGS=(
    userprefs.conf
    keybindings.conf
    windowrules.conf
)

# Note on precedence: hyprland.conf sources userprefs.conf last, so anything set
# there outranks the active theme. Keep structure and behaviour here, and leave
# colors/gaps/rounding/blur to the theme, or theme switching will look broken.
install_hypr_configs() {
    local src="$DESKTOP_DIR/hyde"
    local dest="$XDG_CONFIG/hypr"
    local file

    [[ -d "$src" ]] || return 0

    info "Linking Hyprland user configuration..."

    # Created rather than required: on a fresh machine where Hyprland has never
    # run, ~/.config/hypr may not exist yet, and skipping here would be silent.
    run "mkdir -p '$dest'"

    for file in "${HYPR_USER_CONFIGS[@]}"; do
        if [[ -e "$src/$file" ]]; then
            link_config "$src/$file" "$dest/$file"
        fi
    done
}

# -----------------------------------------------------------------------------
# Lua desktop session
# -----------------------------------------------------------------------------

# Installs a login session that runs this repo's Lua Hyprland config, leaving
# any other session alone. Removing the entry reverts to whatever was there
# before with nothing else touched.
#
# The config is named with --config rather than by exporting HYPRLAND_CONFIG.
# HyDE assigned that variable unconditionally in its own uwsm env fragment, so
# using it would have meant winning an ordering contest inside uwsm's env.d for
# a file this repo does not own. --config is read in preference to the variable
# (verified on 0.56.2) and needs no other file edited.
#
# The entry is a template because the path must be absolute: Desktop Entry
# field codes have nothing for the home directory, and /usr/share/wayland-
# sessions is root-owned and shared between users. It names this checkout's
# real path, so moving the checkout means running this installer again.
#
# The file name is unchanged from when this lived in the dotfiles: sddm
# remembers the last session by it, and a new name would lose that choice.
SESSION_ENTRY="/usr/share/wayland-sessions/hyprland-dotfiles.desktop"

install_desktop_session() {
    local template="$DESKTOP_DIR/session/hyprland-dotfiles.desktop.in"
    local init_lua="$DESKTOP_DIR/init.lua"

    [[ -f "$template" ]] || return 0

    # A config that does not parse must never reach the login screen, where the
    # only way to read the error is from another machine. Hyprland parses it
    # without starting a session, so this costs nothing and catches everything
    # the compositor would have refused.
    info "Verifying the Lua Hyprland configuration..."

    if ! "$DESKTOP_DIR/verify-config.sh" "$init_lua"; then
        echo "Refusing to install the session entry while the config has errors."
        return 1
    fi

    # Verifying the config proved the compositor would accept it and proved
    # nothing about the command line that launches it: a malformed Exec fails
    # inside uwsm's argument parsing, before Hyprland is reached, and a display
    # manager reports that as a failed login rather than a bad command. A dry
    # run writes and starts nothing, so it is safe to do from inside a running
    # session, and it is the only check that covers the Exec line itself.
    local exec_line dry_run_line

    # Read from the template and substituted exactly as the entry will be, so
    # this tests the line the display manager will actually run. Rebuilding an
    # equivalent command here would let the two drift, and a check that passes
    # while the installed entry is broken is worse than no check.
    exec_line="$(sed -n 's/^Exec=//p' "$template" | sed "s|@INIT_LUA@|$init_lua|")"

    if command -v uwsm &> /dev/null && [[ "$exec_line" == uwsm\ start\ * ]]; then
        info "Checking the session command line..."

        dry_run_line="${exec_line/uwsm start/uwsm start -n}"

        if ! eval "$dry_run_line" &> /dev/null; then
            echo "uwsm rejected the session command line:"
            eval "$dry_run_line" 2>&1 | sed 's/^/    /'
            echo ""
            echo "Refusing to install a session entry that cannot start."
            return 1
        fi

        echo "    uwsm accepts it"
    fi

    info "Installing the 'Hyprland (dotfiles)' session..."

    # Needs root: session entries are system-wide. Written via a temporary file
    # so a failed substitution cannot leave a half-written entry that SDDM would
    # still offer.
    local staged="${TMPDIR:-/tmp}/hyprland-dotfiles.desktop.$$"

    if [[ "$DRY_RUN" == true ]]; then
        echo "[dry-run] install $template -> $SESSION_ENTRY (INIT_LUA=$init_lua)"
        return 0
    fi

    sed "s|@INIT_LUA@|$init_lua|" "$template" > "$staged"

    sudo install -Dm644 "$staged" "$SESSION_ENTRY"
    rm -f "$staged"

    echo "    Log out and pick 'Hyprland (dotfiles)' to use it."
}

# -----------------------------------------------------------------------------
# Generated files and the bar
# -----------------------------------------------------------------------------

# Generates every config that carries a colour, from lib/palette.lua. The
# session does this at login too; doing it here means a fresh machine has them
# before its first login rather than one login later.
#
# Cheap and idempotent, so it runs every install: it is also how a palette.lua
# edit reaches the bar.
install_theme() {
    local render="$DESKTOP_DIR/render-theme.lua"

    [[ -x "$render" ]] || return 0

    info "Rendering theme files from the palette..."

    run "lua '$render' --verbose"
}

# The bar ignores generated colours entirely while paletteMode is "static",
# which is its default, so this has to run once before the colours mean
# anything. Idempotent, so it simply runs every install.
install_pill_flags() {
    local script="$DESKTOP_DIR/quickshell/pill-flags.sh"

    [[ -x "$script" ]] || return 0

    info "Setting the bar to use generated colours..."

    run "$script"
}

# The pill shells out to helpers it expects at ~/.config/hypr/scripts. A whole
# directory rather than file-by-file, so a script added to the repo is live
# without touching the installer.
install_pill_scripts() {
    local scripts="$DESKTOP_DIR/quickshell/scripts"

    [[ -d "$scripts" ]] || return 0

    link_config "$scripts" "$XDG_CONFIG/hypr/scripts"
}

# Seeds ~/.config/hypr/hypridle.conf, which is where hypridle looks by default
# and where the bar's idle settings surface writes.
#
# **Copied, and only when absent.** A symlink would have the bar rewriting a
# tracked file in this repo the first time an idle timeout changed. Copying
# once means this repo supplies the defaults and the bar owns the file
# thereafter, which is the right split: timeouts are a preference, not
# architecture.
#
# The consequence to remember: editing the repo's hypridle.conf does not reach a
# machine that already has one.
install_hypridle_conf() {
    local src="$DESKTOP_DIR/hypridle.conf"
    local dest="$XDG_CONFIG/hypr/hypridle.conf"

    [[ -f "$src" ]] || return 0

    if [[ -e "$dest" ]]; then
        echo "Left ${dest/#$HOME/~}: it already exists and the bar may own it."
        return 0
    fi

    info "Seeding the idle configuration..."

    run "mkdir -p '$XDG_CONFIG/hypr'"
    run "cp '$src' '$dest'"
}

# -----------------------------------------------------------------------------
# Run
# -----------------------------------------------------------------------------

install_hypr_configs

install_desktop_session

# All three write generated files outside the repo.
install_theme

install_pill_flags

install_pill_scripts

install_hypridle_conf

echo ""
echo "======================================"
if [[ "$DRY_RUN" == true ]]; then
    echo " Dry run complete: nothing was changed"
else
    echo " Desktop installed"
fi
echo "======================================"
